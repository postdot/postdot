import { existsSync } from 'node:fs'
import { resolve } from 'node:path'

import { Argument, type Command, type Option } from 'commander'

const shells = ['bash', 'zsh', 'fish'] as const
export type CompletionShell = (typeof shells)[number]

function visibleCommands(command: Command) {
    return command.createHelp().visibleCommands(command)
}
function visibleOptions(command: Command): Option[] {
    return [
        ...command.createHelp().visibleOptions(command),
        ...(command.parent ? visibleOptions(command.parent) : []),
    ]
}

/** Inspect grammar only: never parse or execute the command being completed. */
export function completionCandidates(root: Command, words: readonly string[], position: number) {
    if (!Number.isInteger(position) || position < 1 || position > words.length) return []
    let command = root
    let argumentIndex = 0
    let pending: Option | undefined
    let lastValueOption: Option | undefined
    let afterValue = false
    for (let index = 1; index < position; index++) {
        const word = words[index] ?? ''
        if (word === '--') return []
        if (pending) {
            // Bash treats '=' as a word break even in --option=value.
            if (word === '=') continue
            if (pending.required || !word.startsWith('-')) {
                lastValueOption = pending
                pending = undefined
                afterValue = true
                continue
            }
            pending = undefined
        }
        // Bash also splits colons in URLs; consume the rest of that value.
        if (afterValue && (word === ':' || word === '=')) {
            pending = lastValueOption
            continue
        }
        afterValue = false
        if (word.startsWith('-')) {
            const flag = word.split('=', 1)[0]
            const option = visibleOptions(command).find(
                item => item.long === flag || item.short === flag
            )
            if (!option) return []
            if (option.required || option.optional) {
                if (word.includes('=')) {
                    lastValueOption = option
                    afterValue = true
                } else pending = option
            }
            continue
        }
        if (command === root && word === 'help') continue
        const child = visibleCommands(command).find(
            item => item.name() === word || item.aliases().includes(word)
        )
        if (child) {
            command = child
            argumentIndex = 0
            continue
        }
        const argument = command.registeredArguments[argumentIndex]
        if (!argument) return []
        if (!argument.variadic) argumentIndex++
    }
    const prefix = words[position] ?? ''
    if (pending && (pending.required || !prefix.startsWith('-'))) {
        const value = prefix === '=' ? '' : prefix
        return (pending.argChoices ?? []).filter(choice => choice.startsWith(value))
    }
    const equal = prefix.indexOf('=')
    if (prefix.startsWith('-') && equal > 0) {
        const flag = prefix.slice(0, equal)
        const option = visibleOptions(command).find(
            item => item.long === flag || item.short === flag
        )
        return (option?.argChoices ?? [])
            .filter(choice => choice.startsWith(prefix.slice(equal + 1)))
            .map(choice => `${flag}=${choice}`)
    }
    const commands = visibleCommands(command).flatMap(item => [item.name(), ...item.aliases()])
    const choices = command.registeredArguments[argumentIndex]?.argChoices ?? []
    const flags = visibleOptions(command).flatMap(option =>
        [option.short, option.long].filter((flag): flag is string => flag !== undefined)
    )
    const candidates = prefix.startsWith('-')
        ? flags
        : [...commands, ...choices, ...(commands.length || choices.length ? [] : flags)]
    return [...new Set(candidates)].filter(value => value.startsWith(prefix)).sort()
}

function quote(value: string, shell: CompletionShell) {
    return shell === 'fish'
        ? `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
        : `'${value.replaceAll("'", "'\\''")}'`
}
export function completionInvocation() {
    const entry = process.argv[1] ? resolve(process.argv[1]) : undefined
    return [process.execPath, ...(entry && existsSync(entry) ? [entry] : [])]
}

export function completionScript(shell: CompletionShell, invocation: readonly string[]) {
    const call = invocation.map(part => quote(part, shell)).join(' ')
    const header =
        '# Generated by postdot. Regenerate after upgrading or moving the runtime or CLI.\n'
    if (shell === 'bash')
        return (
            header +
            [
                '_postdot_complete() {',
                '    local candidate',
                '    COMPREPLY=()',
                '    while IFS= read -r candidate; do',
                '        [[ -n "$candidate" ]] && COMPREPLY+=("$candidate")',
                `    done < <(${call} __complete "$COMP_CWORD" -- "\${COMP_WORDS[@]}" 2>/dev/null)`,
                '}',
                'complete -o default -F _postdot_complete postdot',
                '',
            ].join('\n')
        )
    if (shell === 'zsh')
        return (
            '#compdef postdot\n' +
            header +
            [
                '_postdot() {',
                '    local output',
                '    local -a candidates request_words',
                '    request_words=("${words[@]}")',
                '    request_words[CURRENT]="$PREFIX"',
                `    output=$(${call} __complete "$((CURRENT - 1))" -- "\${request_words[@]}" 2>/dev/null)`,
                '    if [[ -z "$output" ]]; then _files; return; fi',
                '    candidates=("${(@f)output}")',
                '    compadd -- "${candidates[@]}"',
                '}',
                'compdef _postdot postdot',
                '',
            ].join('\n')
        )
    return (
        header +
        [
            'if test (string split . -- $version)[1] -lt 4',
            "    echo 'Postdot completion requires Fish 4 or later.' >&2",
            '    return 1',
            'end',
            'function __postdot_candidates',
            '    set -l words (commandline -pxc)',
            '    set -l current (commandline -ct)',
            `    ${call} __complete (count $words) -- $words "$current" 2>/dev/null`,
            'end',
            "complete -c postdot -f -a '(__postdot_candidates)'",
            '',
        ].join('\n')
    )
}

export function registerCompletionCommands(program: Command, writeOut: (value: string) => void) {
    program
        .command('completion')
        .description('Print a shell completion script without changing shell configuration.')
        .addArgument(new Argument('<shell>', 'Shell to configure').choices(shells))
        .action((shell: CompletionShell, _options, command: Command) => {
            const script = completionScript(shell, completionInvocation())
            writeOut(
                command.optsWithGlobals<{ json?: boolean }>().json
                    ? `${JSON.stringify({ shell, script })}\n`
                    : script
            )
        })
    program
        .command('__complete', { hidden: true })
        .argument('<position>')
        .argument('[words...]')
        .action((position: string, words: string[] = []) => {
            const candidates = completionCandidates(program, words, Number(position))
            if (candidates.length) writeOut(`${candidates.join('\n')}\n`)
        })
}
