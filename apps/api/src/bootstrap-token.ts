import { createHash, randomBytes, timingSafeEqual } from 'node:crypto'
import { constants } from 'node:fs'
import { chmod, mkdir, open, unlink } from 'node:fs/promises'
import { dirname, join } from 'node:path'

import type { PostdotBootstrapConfig, PostdotConfig } from './config'

const bootstrapTokenMinimumLength = 16
const maxBootstrapTokenFileBytes = 16_384

export interface InstanceBootstrapGuard {
    readonly mode: 'open' | 'token_required'
    readonly verifyToken: (candidate: string) => boolean
    readonly onClaimed: () => Promise<void>
    /** Exposed only when an instance-generated file holds the token for operator logging/tests. */
    readonly tokenFilePath?: string
}

export function hashBootstrapToken(token: string): string {
    return createHash('sha256').update(token, 'utf8').digest('hex')
}

export function normalizeBootstrapTokenHash(rawHash: string): string {
    const match = /^(?:sha256:)?([0-9a-f]{64})$/i.exec(rawHash.trim())
    if (match === null) {
        throw new Error(
            'POSTDOT_BOOTSTRAP_TOKEN_HASH must be a 64-character hexadecimal SHA-256 digest (optionally prefixed with sha256:)'
        )
    }
    return match[1]!.toLowerCase()
}

export function verifyBootstrapTokenDigest(candidate: string, expectedDigestHex: string): boolean {
    if (candidate.length === 0) return false
    const actual = createHash('sha256').update(candidate, 'utf8').digest()
    const expected = Buffer.from(expectedDigestHex, 'hex')
    if (actual.length !== expected.length) return false
    return timingSafeEqual(actual, expected)
}

export async function readBootstrapTokenFile(filePath: string): Promise<string> {
    let file
    try {
        file = await open(
            filePath,
            constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK
        )
    } catch {
        throw new Error(`Bootstrap token file is unreadable or a symbolic link: ${filePath}`)
    }
    try {
        const stat = await file.stat()
        if (!stat.isFile() || stat.size > maxBootstrapTokenFileBytes) {
            throw new Error(
                `Bootstrap token file must be a regular file of at most ${maxBootstrapTokenFileBytes} bytes`
            )
        }
        const token = (await file.readFile('utf8')).trim()
        if (token.length < bootstrapTokenMinimumLength) {
            throw new Error(
                `Bootstrap token file must contain at least ${bootstrapTokenMinimumLength} characters`
            )
        }
        return token
    } finally {
        await file.close()
    }
}

export function resolveBootstrapDataDirectory(
    database: PostdotConfig['database'],
    mediaDirectory: string
): string | null {
    if (database.engine === 'sqlite') {
        return database.fileName === ':memory:' ? null : dirname(database.fileName)
    }
    return dirname(mediaDirectory)
}

async function readExistingAutoBootstrapToken(filePath: string): Promise<string | null> {
    let file
    try {
        file = await open(
            filePath,
            constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK
        )
    } catch (error) {
        const code = (error as NodeJS.ErrnoException | null)?.code
        if (code === 'ENOENT') return null
        throw new Error(
            `Auto-generated bootstrap token file could not be opened safely: ${filePath}`
        )
    }
    try {
        const stat = await file.stat()
        if (!stat.isFile() || stat.size > maxBootstrapTokenFileBytes) {
            throw new Error(`Invalid auto-generated bootstrap token file: ${filePath}`)
        }
        const token = (await file.readFile('utf8')).trim()
        return token.length >= bootstrapTokenMinimumLength ? token : null
    } finally {
        await file.close()
    }
}

async function ensureAutoGeneratedBootstrapToken(
    filePath: string
): Promise<{ readonly token: string; readonly created: boolean }> {
    const existing = await readExistingAutoBootstrapToken(filePath)
    if (existing !== null) {
        return { token: existing, created: false }
    }

    await mkdir(dirname(filePath), { recursive: true })
    const generated = randomBytes(24).toString('base64url')
    try {
        const file = await open(
            filePath,
            constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW,
            0o600
        )
        try {
            await file.writeFile(`${generated}\n`, 'utf8')
            await file.chmod(0o600)
        } finally {
            await file.close()
        }
        return { token: generated, created: true }
    } catch (error) {
        const code = (error as NodeJS.ErrnoException | null)?.code
        if (code === 'EEXIST') {
            const raced = await readExistingAutoBootstrapToken(filePath)
            if (raced !== null) {
                await chmod(filePath, 0o600).catch(() => {})
                return { token: raced, created: false }
            }
        }
        throw error
    }
}

export async function initializeInstanceBootstrapGuard(options: {
    readonly bootstrap: PostdotBootstrapConfig
    readonly database: PostdotConfig['database']
    readonly mediaDirectory: string
    readonly instanceClaimable: boolean
    readonly logInfo?: (message: string) => void
}): Promise<InstanceBootstrapGuard> {
    if (options.bootstrap.mode === 'open') {
        return {
            mode: 'open',
            verifyToken: () => true,
            onClaimed: async () => {},
        }
    }

    if (!options.instanceClaimable) {
        return {
            mode: 'token_required',
            verifyToken: () => false,
            onClaimed: async () => {},
        }
    }

    let expectedDigest: string
    let autoGeneratedFilePath: string | undefined

    if (options.bootstrap.token !== undefined) {
        expectedDigest = hashBootstrapToken(options.bootstrap.token)
    } else if (options.bootstrap.tokenHash !== undefined) {
        expectedDigest = normalizeBootstrapTokenHash(options.bootstrap.tokenHash)
    } else if (options.bootstrap.tokenFile !== undefined) {
        const token = await readBootstrapTokenFile(options.bootstrap.tokenFile)
        expectedDigest = hashBootstrapToken(token)
    } else {
        const dataDirectory = resolveBootstrapDataDirectory(
            options.database,
            options.mediaDirectory
        )
        if (dataDirectory === null) {
            const generated = randomBytes(24).toString('base64url')
            expectedDigest = hashBootstrapToken(generated)
            ;(options.logInfo ?? console.info)(
                `[postdot-bootstrap] One-time bootstrap token (in-memory DB): ${generated}`
            )
        } else {
            autoGeneratedFilePath = join(dataDirectory, 'bootstrap-token')
            const result = await ensureAutoGeneratedBootstrapToken(autoGeneratedFilePath)
            expectedDigest = hashBootstrapToken(result.token)
            if (result.created) {
                ;(options.logInfo ?? console.info)(
                    `[postdot-bootstrap] One-time bootstrap token written to ${autoGeneratedFilePath} (0600): ${result.token}`
                )
            } else {
                ;(options.logInfo ?? console.info)(
                    `[postdot-bootstrap] Using existing one-time bootstrap token at ${autoGeneratedFilePath}`
                )
            }
        }
    }

    return {
        mode: 'token_required',
        verifyToken: candidate => verifyBootstrapTokenDigest(candidate, expectedDigest),
        onClaimed: async () => {
            if (autoGeneratedFilePath !== undefined) {
                await unlink(autoGeneratedFilePath).catch(() => {})
            }
        },
        ...(autoGeneratedFilePath === undefined ? {} : { tokenFilePath: autoGeneratedFilePath }),
    }
}
